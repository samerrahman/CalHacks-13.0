// Generates src/ui/forest-layers.css: the start screen's night forest as four silhouette layers
// (far, mid, near, framing pines), each an inline SVG custom property. Deterministic; run with
// `node tools/forest-backdrop.mjs` after changing the shapes.
import { writeFile } from 'node:fs/promises';

let seed = 9071;
const random = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
const between = (a, b) => a + random() * (b - a);

/** A ragged pine: stacked drooping tiers that narrow toward a thin tip. */
function pine(x, base, height, width) {
  const tiers = Math.round(between(7, 11)), left = [], right = [];
  for (let t = 0; t < tiers; t++) {
    const y = base - height * (t + .6) / tiers, half = width * .5 * (1 - t / tiers) ** .9 * between(.7, 1.15), droop = height / tiers * between(.3, .6);
    left.push(`${(x - half + between(-3, 3)).toFixed(0)} ${(y + droop).toFixed(0)}`, `${(x - half * .3).toFixed(0)} ${(y + droop * .2).toFixed(0)}`);
    right.unshift(`${(x + half * .3).toFixed(0)} ${(y + droop * .2).toFixed(0)}`, `${(x + half + between(-3, 3)).toFixed(0)} ${(y + droop).toFixed(0)}`);
  }
  const trunk = Math.max(2, width * .05);
  return `M${(x - trunk).toFixed(0)} ${base} L${left.join(' L')} L${x.toFixed(0)} ${(base - height - between(6, 18)).toFixed(0)} L${right.join(' L')} L${(x + trunk).toFixed(0)} ${base}Z`;
}
function layer({ count, base, height, width, color, lights = 0, spread = 1, clearing = 0 }) {
  const W = 1600, H = 900, paths = [];
  for (let i = 0; i < count; i++) {
    let x = between(-40, W + 40);
    // Keep a clearing open in the middle by pushing trees out toward the sides.
    if (clearing && Math.abs(x - W / 2) < W * clearing) x = W / 2 + Math.sign(x - W / 2 || 1) * (W * clearing + between(0, 120));
    const h = between(...height) * (1 + Math.abs(x - W / 2) / (W / 2) * spread * .5);
    paths.push(`<path d='${pine(x, base + between(-12, 12), h, h * between(...width))}'/>`);
  }
  let glow = '';
  for (let i = 0; i < lights; i++) { const x = between(260, 1340), y = base - between(30, 70); glow += `<circle cx='${x.toFixed(0)}' cy='${y.toFixed(0)}' r='5' fill='%23ffb36a'/><circle cx='${x.toFixed(0)}' cy='${y.toFixed(0)}' r='16' fill='%23ff9a4a' opacity='.18'/>`; }
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${W} ${H}' preserveAspectRatio='xMidYMax slice'><rect y='${base}' width='${W}' height='${H - base}' fill='${color}'/><g fill='${color}'>${paths.join('')}</g>${glow}</svg>`;
  return `url("data:image/svg+xml,${svg.replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E')}")`;
}
/** Two huge pines right at the edges, close to the viewer and out of focus. */
function frame(color) {
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 1600 900' preserveAspectRatio='xMidYMax slice'><g fill='${color}'><path d='${pine(70, 960, 1150, .62)}'/><path d='${pine(1530, 960, 1080, .6)}'/><path d='${pine(-60, 940, 760, .7)}'/><path d='${pine(1680, 940, 820, .7)}'/></g></svg>`;
  return `url("data:image/svg+xml,${svg.replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E')}")`;
}

const layers = {
  far: layer({ count: 70, base: 560, height: [120, 210], width: [.32, .42], color: '#26312c' }),
  mid: layer({ count: 40, base: 640, height: [170, 290], width: [.32, .46], color: '#121a16', lights: 3, clearing: .08 }),
  near: layer({ count: 18, base: 780, height: [230, 400], width: [.34, .48], color: '#070a09', spread: 1.6, clearing: .2 }),
  frame: frame('#020303'),
};
const css = `/* Generated by tools/forest-backdrop.mjs. Do not edit by hand. */\n:root{${Object.entries(layers).map(([name, value]) => `--forest-${name}:${value}`).join(';')}}\n`;
await writeFile(new URL('../src/ui/forest-layers.css', import.meta.url), css);
